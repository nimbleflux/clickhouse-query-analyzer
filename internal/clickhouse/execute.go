type ColumnInfo struct {
	Name string `json:"name"`
	Type string `json:"type"`
}

// extractHTTPCode pulls the leading "Code: N" out of a ClickHouse HTTP
// error body. Returns 0 if no code is present.
func extractHTTPCode(body string) ClickHouseErrorCode {
	idx := strings.Index(body, "Code:")
	if idx < 0 {
		return CHUnknown
	}
	rest := body[idx+len("Code:"):]
	rest = strings.TrimLeft(rest, " \t")
	end := 0
	for end < len(rest) && rest[end] >= '0' && rest[end] <= '9' {
		end++
	}
	if end == 0 {
		return CHUnknown
	}
	n, err := strconv.Atoi(rest[:end])
	if err != nil {
		return CHUnknown
	}
	return ClickHouseErrorCode(n)
}

type QueryResult struct {
	Columns   []ColumnInfo     `json:"columns"`
	Rows      []map[string]any `json:"rows"`
	RowCount  int              `json:"row_count"`
	TotalRows int64            `json:"total_rows"`
	TimingMs  int64            `json:"timing_ms"`
	QueryID   string           `json:"query_id"`
	// IsText marks a result that is the raw output of a user-specified FORMAT
	// clause (e.g. FORMAT Vertical / Pretty / TSV) rather than a parsed table.
	// Output holds that text and the editor renders it verbatim.
	IsText bool   `json:"is_text"`
	Output string `json:"output"`
	// Advisor is set when the executed SQL appears to read remote-backed
	// tables (S3/URL/Iceberg/…); it carries warnings and quick actions.
	Advisor *QueryAdvisor `json:"advisor,omitempty"`
}

// isSelectLike returns true if the query looks like a SELECT (or WITH/EXPLAIN/VALUES)
// that returns rows and can therefore be wrapped for pagination. Non-SELECT
// statements (INSERT, CREATE, DROP, ALTER, SET, USE, …) are executed as-is.
// formatClauseRe detects a user-specified `FORMAT <name>` suffix. We don't wrap
// or JSON-parse such queries: ClickHouse honors the clause and returns that
// format's text, which we surface verbatim. (Best-effort: a FORMAT inside a
// string literal is rare enough to ignore.)
var formatClauseRe = regexp.MustCompile(`(?i)\bFORMAT\s+[A-Za-z_]`)

func hasFormatClause(query string) bool {
	return formatClauseRe.MatchString(query)
}

// StripLeadingComments removes leading SQL comments (`-- …` and `/* … *​/`)
// so classification and read-only checks see the actual statement. The loop
// handles stacked comments. Unterminated comments return the empty string —
// such a query is a syntax error anyway, and for rejectWriteQuery failing
// closed is the safe default.
func StripLeadingComments(query string) string {
	trimmed := strings.TrimSpace(query)
	for {
		trimmed = strings.TrimSpace(trimmed)
		switch {
		case strings.HasPrefix(trimmed, "--"):
			nl := strings.IndexByte(trimmed, '\n')
			if nl < 0 {
				return ""
			}
			trimmed = trimmed[nl+1:]
			continue
		case strings.HasPrefix(trimmed, "/*"):
			end := strings.Index(trimmed, "*/")
			if end < 0 {
				return ""
			}
			trimmed = trimmed[end+2:]
			continue
		}
		return trimmed
	}
}

func isSelectLike(query string) bool {
	trimmed := StripLeadingComments(query)
	if trimmed == "" {
		return false
	}
	upper := strings.ToUpper(trimmed)
	switch {
	case strings.HasPrefix(upper, "SELECT"),
		strings.HasPrefix(upper, "WITH"),
		strings.HasPrefix(upper, "EXPLAIN"),
		strings.HasPrefix(upper, "VALUES"),
		strings.HasPrefix(upper, "SHOW"),
		strings.HasPrefix(upper, "DESCRIBE"),
		strings.HasPrefix(upper, "DESC"):
		return true
	}
	return false
}

// ExecuteOptions carries one ad-hoc statement plus its execution knobs.
type ExecuteOptions struct {
	Query  string
	Limit  int
	Offset int
	// Settings are appended to the request URL as ClickHouse settings
	// (filtered through FilterSettings).
	Settings map[string]string
	// Params are named values for {{name}} placeholders. Placeholders are
	// rewritten to ClickHouse parameter expressions ({name:Type}) and the
	// values travel as param_<name> URL parameters — properly quoted by the
	// server, no string splicing into SQL.
	Params map[string]string
	// QueryID is generated by the caller (the HTTP handler) so it is known
	// before execution starts. The handler uses it to poll progress and to
	// KILL the query when the browser disconnects or hits Cancel.
	QueryID string
}

var (
	placeholderRe = regexp.MustCompile(`\{\{(\w+)\}\}`)
	intParamRe    = regexp.MustCompile(`^[+-]?\d{1,18}$`)
	floatParamRe  = regexp.MustCompile(`^[+-]?(\d+\.\d*|\.\d+|\d+)([eE][+-]?\d+)?$`)
)

// inferParamType picks the ClickHouse parameter type for a value. Numbers
// bind as numbers (so `id = {p}` uses index-friendly comparisons), booleans
// as Bool, everything else as String.
func inferParamType(v string) string {
	t := strings.TrimSpace(v)
	switch {
	case t == "true" || t == "false":
		return "Bool"
	case intParamRe.MatchString(t):
		return "Int64"
	case floatParamRe.MatchString(t):
		return "Float64"
	default:
		return "String"
	}
}

// rewritePlaceholders converts {{name}} placeholders into ClickHouse
// parameter expressions and returns the names that were rewritten. A
// backslash-escaped \{{name}} is restored verbatim. Unknown names stay as
// {{name}} so the server rejects the query loudly instead of silently
// binding nothing.
func rewritePlaceholders(query string, params map[string]string) (string, []string) {
	// Protect escaped sequences from the rewrite.
	const escSentinel = "\x00CLICKLENS_ESCAPED_PLACEHOLDER\x00"
	query = strings.ReplaceAll(query, `\{{`, escSentinel)

	var bound []string
	rewritten := placeholderRe.ReplaceAllStringFunc(query, func(m string) string {
		name := placeholderRe.FindStringSubmatch(m)[1]
		v, ok := params[name]
		if !ok {
			return m
		}
		bound = append(bound, name)
		return "{" + name + ":" + inferParamType(v) + "}"
	})
	rewritten = strings.ReplaceAll(rewritten, escSentinel, "{{")
	return rewritten, bound
}

// stripTrailingSemicolon removes trailing semicolons/whitespace so the query
// can be safely embedded inside a parenthesised subquery.
func stripTrailingSemicolon(query string) string {
	return strings.TrimRight(strings.TrimSpace(query), "; \t\r\n")
}

// NewQueryID generates the query_id handed to ClickHouse for ad-hoc editor
// queries. Generating it in the handler (rather than letting ClickHouse pick
// one) means the browser knows the id before the query starts, so progress
// polling and Cancel → KILL QUERY can target it precisely.
func NewQueryID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		// crypto/rand never fails on Linux; fall back to a time-based id.
		return strconv.FormatInt(time.Now().UnixNano(), 36)
	}
	return hex.EncodeToString(b[:])
}

// prepareExecutedQuery decides how a user statement runs:
//
//   - SELECT-like queries without a FORMAT clause are wrapped in a
//     deterministic LIMIT/OFFSET window. The newlines around the user SQL
//     inside the subquery are load-bearing: a query ending in a `--` line
//     comment would otherwise comment out the closing paren and the LIMIT.
//   - Everything else (FORMAT queries, DDL/DML, SHOW GRANTS) runs verbatim.
//
// Returns the statement to execute, whether it was wrapped, and whether the
// raw query carried a FORMAT clause (the response is then opaque text).
func prepareExecutedQuery(query string, limit, offset int) (executed string, wrapped bool, hasFormat bool) {
	hasFormat = hasFormatClause(query)
	selectLike := isSelectLike(query)
	// SHOW GRANTS can't be used as a subquery source — ClickHouse's
	// FROM-clause parser rejects it with SYNTAX_ERROR.
	upper := strings.ToUpper(strings.TrimSpace(query))
	isShowGrants := strings.HasPrefix(upper, "SHOW GRANTS")

	if selectLike && !hasFormat && !isShowGrants {
		return fmt.Sprintf("SELECT * FROM (\n%s\n) LIMIT %d OFFSET %d", stripTrailingSemicolon(query), limit, offset), true, false
	}
	return query, false, hasFormat
}

// allowedSettings and allowedSettingPrefixes define which ClickHouse settings
// the editor may set. Deny-by-default matters: an unrestricted map lets a
// caller spoof `log_comment` (making their queries look like ClickLens's own,
// hiding them from the query list) or toggle profilers on unrelated work.
var allowedSettings = map[string]bool{
	"log_queries": true, "log_query_threads": true, "log_profile_events": true,
	"log_query_views": true, "log_query_metrics": true,
	"query_profiler_real_time_period_ns": true, "query_profiler_cpu_time_period_ns": true,
	"allow_introspection_functions": true,
	"max_execution_time":            true, "max_threads": true, "max_memory_usage": true,
	"max_bytes_to_read": true, "max_result_bytes": true, "max_download_buffer_size": true,
	"use_query_cache": true, "query_cache_ttl": true, "query_cache_min_query_duration": true,
	"query_cache_min_query_runs": true, "query_cache_share_quota_with_filling_filesystem_cache": true,
	"aggregate_functions_null_for_empty": true, "date_time_input_format": true,
	"date_time_output_format": true, "session_timezone": true,
	"result_overflow_mode": true, "timeout_before_checking_execution_speed": true,
	"query_plan_optimize_lazy_materialization_for_object_storage": true,
}

var allowedSettingPrefixes = []string{"query_plan_", "optimize_", "timeout_", "max_", "use_", "force_"}

func settingAllowed(key string) bool {
	if allowedSettings[key] {
		return true
	}
	for _, p := range allowedSettingPrefixes {
		if strings.HasPrefix(key, p) {
			return true
		}
	}
	return false
}

// FilterSettings drops any key not on the allowlist. Returns nil when nothing
// survives so callers can skip work.
func FilterSettings(in map[string]string) map[string]string {
	if len(in) == 0 {
		return nil
	}
	var out map[string]string
	for k, v := range in {
		if settingAllowed(k) {
			if out == nil {
				out = make(map[string]string, len(in))
			}
			out[k] = v
		}
	}
	return out
}

func (c *Client) ExecuteQuery(ctx context.Context, opts ExecuteOptions) (*QueryResult, error) {
	if opts.Limit <= 0 {
		opts.Limit = 100
	}
	if opts.Offset < 0 {
		opts.Offset = 0
	}
	if opts.QueryID == "" {
		opts.QueryID = NewQueryID()
	}

	query := opts.Query
	if len(opts.Params) > 0 {
		rewritten, _ := rewritePlaceholders(query, opts.Params)
		query = rewritten
	}
	executedQuery, _, hasFormat := prepareExecutedQuery(query, opts.Limit, opts.Offset)

	httpURL, err := c.httpURL()
	if err != nil {
		return nil, err
	}

	start := time.Now()

	u, _ := url.Parse(httpURL)
	q := u.Query()
	for k, v := range FilterSettings(opts.Settings) {
		q.Set(k, v)
	}
	// Bind parameter values server-side: param_<name> + {name:Type}
	// placeholders in the SQL. ClickHouse quotes the values itself, which
	// removes the whole class of quoting bugs/injection from the old
	// frontend string substitution. Extra param_ values are harmless.
	for name, v := range opts.Params {
		q.Set("param_"+name, v)
	}
	// log_comment is what marks ClickLens's own queries in query_log; it must
	// never be settable from the request or the "hide internal queries"
	// filters could be spoofed.
	q.Set("log_comment", "")
	// The caller-generated query_id is what progress polling and KILL QUERY
	// target; sending it explicitly also makes the query visible in
	// system.processes under a stable id the browser already knows.
	q.Set("query_id", opts.QueryID)
	// enable_http_compression makes ClickHouse gzip the response; Go's
	// transport transparently decompresses it. Large JSON result pages
	// compress ~10x.
	q.Set("enable_http_compression", "1")
	// Apply defense-in-depth limits AFTER user settings so they can't be
	// overridden by the client (e.g. sending max_result_rows=999999999).
	q.Set("max_result_rows", fmt.Sprintf("%d", opts.Limit))
	q.Set("result_overflow_mode", "break")
	u.RawQuery = q.Encode()

	body := bytes.NewBufferString(executedQuery)
	req, err := http.NewRequestWithContext(ctx, "POST", u.String(), body)
	if err != nil {
		return nil, fmt.Errorf("creating request: %w", err)
	}
	req.Header.Set("Content-Type", "text/plain")

	resp, err := c.getHTTPClient().Do(req)
	if err != nil {
		return nil, fmt.Errorf("executing query: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != 200 {
		b, _ := io.ReadAll(resp.Body)
		return nil, &CHError{
			Code:    extractHTTPCode(string(b)),
			Message: strings.TrimSpace(string(b)),
		}
	}

	// A user-specified FORMAT clause (e.g. FORMAT Vertical) makes ClickHouse
	// return that format's text, which isn't the JSON we parse below. Surface
	// it verbatim so Vertical/Pretty/TSV/etc. render as the user asked.
	if hasFormat {
		b, _ := io.ReadAll(resp.Body)
		return &QueryResult{
			IsText:   true,
			Output:   string(b),
			Columns:  []ColumnInfo{},
			Rows:     []map[string]any{},
			TimingMs: time.Since(start).Milliseconds(),
			QueryID:  opts.QueryID,
		}, nil
	}

	dec := json.NewDecoder(resp.Body)

	var names []string
	if !dec.More() {
		return &QueryResult{
			Columns:   []ColumnInfo{},
			Rows:      []map[string]any{},
			RowCount:  0,
			TotalRows: -1,
			TimingMs:  time.Since(start).Milliseconds(),
			QueryID:   opts.QueryID,
		}, nil
	}

	var namesRaw []json.RawMessage
	if err := dec.Decode(&namesRaw); err != nil {
		return nil, fmt.Errorf("parsing column names: %w", err)
	}
	for _, r := range namesRaw {
		var name string
		json.Unmarshal(r, &name)
		names = append(names, name)
	}

	var types []string
	if !dec.More() {
		return &QueryResult{
			Columns:   columnsFromNamesTypes(names, nil),
			Rows:      []map[string]any{},
			RowCount:  0,
			TotalRows: -1,
			TimingMs:  time.Since(start).Milliseconds(),
			QueryID:   opts.QueryID,
		}, nil
	}
	var typesRaw []json.RawMessage
	if err := dec.Decode(&typesRaw); err != nil {
		return nil, fmt.Errorf("parsing column types: %w", err)
	}
	for _, r := range typesRaw {
		var t string
		json.Unmarshal(r, &t)
		types = append(types, t)
	}

	columns := columnsFromNamesTypes(names, types)

	var result []map[string]any
	rowIdx := 0
	for dec.More() {
		var vals []json.RawMessage
		if err := dec.Decode(&vals); err != nil {
			break
		}
		row := make(map[string]any, len(names))
		for i, name := range names {
			if i < len(vals) {
				var v any
				if err := json.Unmarshal(vals[i], &v); err != nil {
					var s string
					json.Unmarshal(vals[i], &s)
					v = s
				}
				row[name] = v
			}
		}
		result = append(result, row)
		rowIdx++
		if rowIdx >= opts.Limit {
			break
		}
	}

	return &QueryResult{
		Columns:   columns,
		Rows:      result,
		RowCount:  len(result),
		TotalRows: -1,
		TimingMs:  time.Since(start).Milliseconds(),
		QueryID:   opts.QueryID,
	}, nil
}

// CountQueryRows runs an explicit, user-initiated `SELECT count() FROM (<query>)`.
// This used to happen automatically on every first page, which silently
// doubled the cost of heavy queries (two full S3 scans, for example). It is
// now opt-in from the UI. Returns -1 when the query isn't countable or the
// count itself fails.
func (c *Client) CountQueryRows(ctx context.Context, query string) (int64, error) {
	if !isSelectLike(query) || hasFormatClause(query) {
		return -1, nil
	}
	upper := strings.ToUpper(strings.TrimSpace(query))
	if strings.HasPrefix(upper, "SHOW GRANTS") {
		return -1, nil
	}
	countQuery := fmt.Sprintf("SELECT count() FROM (\n%s\n)", stripTrailingSemicolon(query))
	result, err := c.ExecuteQuery(ctx, ExecuteOptions{Query: countQuery, Limit: 1})
	if err != nil {
		return -1, err
	}
	if len(result.Rows) == 0 {
		return -1, nil
	}
	first := result.Rows[0]
	for _, v := range first {
		switch n := v.(type) {
		case float64:
			return int64(n), nil
		case string:
			if parsed, perr := strconv.ParseInt(n, 10, 64); perr == nil {
				return parsed, nil
			}
			return -1, nil
		}
	}
	return -1, nil
}

// QueryProgress is a live snapshot of a running query from system.processes.
type QueryProgress struct {
	ElapsedSec      float64 `json:"elapsed_sec"`
	ReadRows        uint64  `json:"read_rows"`
	ReadBytes       uint64  `json:"read_bytes"`
	TotalRowsApprox uint64  `json:"total_rows_approx"`
	MemoryUsage     uint64  `json:"memory_usage"`
	Progress        float64 `json:"progress"` // 0..1, ClickHouse's own estimate
	IsRunning       bool    `json:"is_running"`
}

// GetProgress polls system.processes for a running query by query_id.
// A query that already finished (or was killed) reports IsRunning=false
// rather than an error — polling races completion all the time.
func (c *Client) GetProgress(ctx context.Context, queryID string) (*QueryProgress, error) {
	var p QueryProgress
	// memory_usage is Int64 and there is no `progress` column on modern
	// servers (26.x removed it) — progress is derived from read_rows against
	// total_rows_approx when an estimate exists.
	var memoryUsage int64
	q := fmt.Sprintf(`
		SELECT elapsed, read_rows, read_bytes, total_rows_approx, memory_usage
		FROM %s
		WHERE query_id = ?
		LIMIT 1`, c.tableRef("processes"))
	err := c.conn.QueryRow(ctx, q, queryID).Scan(
		&p.ElapsedSec, &p.ReadRows, &p.ReadBytes, &p.TotalRowsApprox, &memoryUsage)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return &QueryProgress{IsRunning: false}, nil
		}
		return nil, err
	}
	if memoryUsage > 0 {
		p.MemoryUsage = uint64(memoryUsage)
	}
	if p.TotalRowsApprox > 0 {
		p.Progress = float64(p.ReadRows) / float64(p.TotalRowsApprox)
		if p.Progress > 1 {
			p.Progress = 1
		}
	}
	p.IsRunning = true
	return &p, nil
}

func columnsFromNamesTypes(names []string, types []string) []ColumnInfo {
	cols := make([]ColumnInfo, len(names))
	for i, n := range names {
		cols[i] = ColumnInfo{Name: n}
		if i < len(types) {
			cols[i].Type = types[i]
		}
	}
	return cols
}

func nativeToHTTPPort(nativePort string) string {
	switch nativePort {
	case "9000", "":
		return "8123"
	case "9440":
		return "8443"
	default:
		n, err := strconv.Atoi(nativePort)
		if err != nil {
			return "8123"
		}
		return fmt.Sprintf("%d", n-877)
	}
}

func (c *Client) getHTTPClient() *http.Client {
	return c.httpClient
}

func (c *Client) httpURL() (string, error) {
	if c.connURL == "" {
		return "", fmt.Errorf("connection URL not available")
	}
	u, err := url.Parse(c.connURL)
	if err != nil {
		return "", fmt.Errorf("parsing URL: %w", err)
	}

	if c.isHTTP {
		u.User = url.UserPassword(c.connUser, c.connPass)
		u.Path = "/"
		q := u.Query()
		q.Set("default_format", "JSONCompactEachRowWithNamesAndTypes")
		u.RawQuery = q.Encode()
		return u.String(), nil
	}

	switch u.Scheme {
	case "clickhouse":
		u.Scheme = "http"
	case "clickhouses":
		u.Scheme = "https"
	}
	host := u.Hostname()
	u.Host = host + ":" + nativeToHTTPPort(u.Port())
	u.User = url.UserPassword(c.connUser, c.connPass)
	u.Path = "/"
	q := u.Query()
	q.Set("default_format", "JSONCompactEachRowWithNamesAndTypes")
	u.RawQuery = q.Encode()
	return u.String(), nil
}

type TableInfo struct {
	Name     string       `json:"name"`
	Engine   string       `json:"engine"`
	RowCount uint64       `json:"row_count"`
	Columns  []ColumnInfo `json:"columns"`
}

type DatabaseInfo struct {
	Name   string      `json:"name"`
	Tables []TableInfo `json:"tables"`
}

type SchemaInfo struct {
	Databases []DatabaseInfo `json:"databases"`
}

func (c *Client) GetDatabases(ctx context.Context) ([]string, error) {
	rows, err := c.conn.Query(ctx, "SELECT name FROM system.databases WHERE name NOT IN ('INFORMATION_SCHEMA', 'information_schema') ORDER BY name")
	if err != nil {
		return nil, fmt.Errorf("querying databases: %w", err)
	}
	defer rows.Close()
	var databases []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, err
		}
		databases = append(databases, name)
	}
	return databases, nil
}

func (c *Client) GetTables(ctx context.Context, database string) ([]TableInfo, error) {
	tRows, err := c.conn.Query(ctx, "SELECT name, engine, total_rows FROM system.tables WHERE database = ? ORDER BY name", database)
	if err != nil {
		return nil, err
	}
	defer tRows.Close()
	var tables []TableInfo
	for tRows.Next() {
		var name, engine string
		var totalRows uint64
		if err := tRows.Scan(&name, &engine, &totalRows); err != nil {
			return nil, err
		}
		tables = append(tables, TableInfo{Name: name, Engine: engine, RowCount: totalRows})
	}
	return tables, nil
}

func (c *Client) GetColumns(ctx context.Context, database, table string) ([]ColumnInfo, error) {
	cRows, err := c.conn.Query(ctx, "SELECT name, type FROM system.columns WHERE database = ? AND table = ? ORDER BY position", database, table)
	if err != nil {
		return nil, err
	}
	defer cRows.Close()

	var columns []ColumnInfo
	for cRows.Next() {
		var name, typ string
		if err := cRows.Scan(&name, &typ); err != nil {
			return nil, err
		}
		columns = append(columns, ColumnInfo{Name: name, Type: typ})
	}
	return columns, nil
}

func isProbablyJSON(s string) bool {
	s = strings.TrimSpace(s)
	return len(s) > 0 && (s[0] == '{' || s[0] == '[')
}

// GetTableDDL returns the SHOW CREATE statement for a table. Identifiers are
// quoted (they come from system tables but may be reserved words).
func (c *Client) GetTableDDL(ctx context.Context, database, table string) (string, error) {
	var stmt string
	q := fmt.Sprintf("SHOW CREATE TABLE %s.%s", quoteIdent(database), quoteIdent(table))
	if err := c.conn.QueryRow(ctx, q).Scan(&stmt); err != nil {
		return "", fmt.Errorf("show create %s.%s: %w", database, table, err)
	}
	return stmt, nil
}
